"""Rebuild gloss.json: re-derive every entry's exact word text ('w') from data.json and its quran.com word-by-word
English ('wbw') from tools/cache, check every key, and write the result back. Curated fields are kept as they are.
usage: python build_gloss.py [--src <file with {"words": {...}}>] [--out <file>]
       (defaults: --src and --out are apps/quran-map/gloss.json; use --out to check a draft without touching the app)
"""
import json, os, re, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from paths import CACHE, DATA, GLOSS, SOURCES

sys.stdout.reconfigure(encoding='utf-8')
args = sys.argv[1:]
opt = lambda name, default: args[args.index(name) + 1] if name in args else default
src_p, out_p = opt('--src', GLOSS), opt('--out', GLOSS)
words_in = json.load(open(src_p, encoding='utf-8'))['words']
data = json.load(open(DATA, encoding='utf-8'))
isword = lambda t: bool(re.search('[ء-يٱ]', t))

cache = {}
def wbw(surah):
    if surah not in cache:
        p = os.path.join(CACHE, f'wbw{surah}.json')
        verses = json.load(open(p, encoding='utf-8'))['verses'] if os.path.exists(p) else []
        cache[surah] = {int(v['verse_key'].split(':')[1]): [w for w in v['words'] if w['char_type_name'] == 'word'] for v in verses}
    return cache[surah]

out, problems = {}, []
for key, e in sorted(words_in.items(), key=lambda kv: tuple(map(int, kv[0].split(':')))):
    s, a, w = map(int, key.split(':'))
    toks = data[s - 1]['a'][a - 1].split(' ')
    if w > len(toks): problems.append(f'{key}: ayah has only {len(toks)} tokens'); continue
    flags = [isword(t) for t in toks]
    if not flags[w - 1]: problems.append(f'{key}: position {w} is a pause mark, not a word'); continue
    curated = {k: v for k, v in e.items() if k not in ('w', 'wbw')}
    entry = {'w': toks[w - 1]}
    words = wbw(s).get(a)
    if words is None:
        if 'wbw' in e: entry['wbw'] = e['wbw']                # no cache for this surah: keep the stored gloss
        else: problems.append(f'{key}: no cached word-by-word (run fetch.py {s})')
    else:
        if sum(flags) != len(words): problems.append(f'{key}: {sum(flags)} text words vs {len(words)} quran.com words')
        wi = sum(flags[:w]) - 1
        if wi < len(words): entry['wbw'] = words[wi]['translation']['text'].strip()
    for f in ('tr', 'en', 'ar', 'src'):
        if not curated.get(f): problems.append(f'{key}: missing {f}')
    entry.update(curated)
    out[key] = entry

doc = {
    '_about': "Word notes for the Quran Map reader: only the essential words of each surah. Key = surah:ayah:word "
              "(1-based position in the ayah text split on spaces). 'w' and 'wbw' are generated by tools/build_gloss.py "
              "from data.json and quran.com word-by-word; the rest is curated from the sources listed in 'src'.",
    'sources': SOURCES,
    'words': out,
}
json.dump(doc, open(out_p, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
print(f'entries {len(out)} -> {out_p}')
for p in problems: print('PROBLEM', p)
if '-v' in args:
    for k, v in out.items(): print(k, v['w'], '=', v.get('wbw'))
